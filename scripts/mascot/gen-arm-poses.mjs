#!/usr/bin/env node
// Solves every ARM_TARGETS entry for both arms with the exact arm chain the renderer draws and writes
// packages/renderer/src/mascot/rig/armPoses.generated.ts.
//   node scripts/mascot/gen-arm-poses.mjs [--check]
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const rigDir = path.join(root, 'packages/renderer/src/mascot/rig');
const out = path.join(rigDir, 'armPoses.generated.ts');
const tmp = path.join(os.tmpdir(), `nomi-gen-arm-${process.pid}.mjs`);
const entry = `
import { ARM_TARGETS } from ${JSON.stringify(path.join(rigDir, 'armTargets.ts'))};
import { reach, mirror } from ${JSON.stringify(path.join(rigDir, 'armReach.ts'))};
const res = {}; const fails = [];
for (const [name, t] of Object.entries(ARM_TARGETS)) {
  try {
    const o = { angle: t.angle, z: t.z, elbow: t.elbow, hint: t.hint };
    const r = reach('r', t.hand, t.t, o);
    const l = reach('l', t.hand, mirror(t.t), { ...o, angle: -t.angle, near: [r[0], r[1]] });
    res[name] = { r, l };
  } catch (e) { fails.push(name + ': ' + e.message); }
}
export { res, fails };
`;
await build({
  stdin: { contents: entry, resolveDir: rigDir, loader: 'ts' },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: tmp,
  logLevel: 'error',
});
const { res, fails } = await import(pathToFileURL(tmp).href);
fs.rmSync(tmp, { force: true });
if (fails.length) {
  console.error('unreachable targets:\n  ' + fails.join('\n  '));
  if (!process.argv.includes('--keep-going')) process.exit(1);
}
const r1 = (x) => Math.round(x * 100) / 100;
const clampE = (p) => { p[1] = Math.max(-110, Math.min(110, p[1])); p[2] = Math.max(-45, Math.min(45, p[2])); return p; };
let body = `/**\n * GENERATED by scripts/mascot/gen-arm-poses.mjs from armTargets.ts — do not edit.\n * Arm poses [a, e, w] in degrees and z (0..1) for the screen-right arm (r) and its mirror (l).\n */\nexport type ArmPose = readonly [a: number, e: number, w: number, z: number];\nexport const ARM_POSES = {\n`;
for (const [n, v] of Object.entries(res))
  body += `  ${n}: { r: [${clampE([...v.r]).map(r1).join(', ')}], l: [${clampE([...v.l]).map(r1).join(', ')}] },\n`;
body += `} as const satisfies Record<string, { r: ArmPose; l: ArmPose }>;\n`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) {
    console.error('armPoses.generated.ts is stale: run node scripts/mascot/gen-arm-poses.mjs');
    process.exit(1);
  }
  console.info('arm poses ok');
} else {
  fs.writeFileSync(out, body);
  console.info('wrote', path.relative(root, out), Object.keys(res).length, 'poses');
}
