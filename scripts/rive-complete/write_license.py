#!/usr/bin/env python3
"""Write rive/nomi-complete/parts/DETAIL_LICENSE.json + rive/nomi-complete/LICENSE.
Every AI-generated asset (the three owner-generated arm/hand/sleeve images and everything derived from them) is marked
ai_generated: true; official-derived / procedural files (r2, no longer embedded in the scene) stay ai_generated: false."""
import hashlib, json
from pathlib import Path
R = Path(__file__).resolve().parents[2] / 'rive/nomi-complete'
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
old = json.loads((R / 'parts/DETAIL_LICENSE.json').read_text())
assets = {}
for k, v in old['assets'].items():
    if 'ai_generated' in v and v['ai_generated'] is False and 'in_scene' not in v:
        v = dict(v); v['in_scene'] = False; v['note'] = 'r2 official cut/restore texture; superseded by the AI pose-state art in r3 (kept for the r2 build script)'
    assets[k] = v
SRC = {'gen-arm-hang': 'hang', 'gen-arm-wave-bent': 'bent', 'gen-arm-cheer-up': 'up'}
def add(path, derived_from, method, ai=True):
    p = R / path
    assets[path] = dict(sha256=sha(p), bytes=p.stat().st_size, ai_generated=ai, in_scene=not path.startswith('gen-src') and 'gen-arm-' not in path,
                        derived_from=derived_from, method=method,
                        scope='sleeve / forearm / hand / cuff only - no head, hair, hairclip, N logo, badge, jacket body or face pixels')
for n, st in SRC.items():
    add(f'gen-src/{n}.jpg', None, 'owner-generated with AI image tools (reference: official half-body + earlier generated parts); green #00FF00 background, 1280x720')
    add(f'parts/ai/{n}.png', f'gen-src/{n}.jpg', 'chroma-key (green dominance alpha, despill, speck removal), native resolution, no resampling')
    for sd in 'rl':
        add(f'parts/ai/arm-{st}-{sd}.png', f'parts/ai/{n}.png', 'crop to arm/hand/cuff (torso pocket/hood/collar removed), colour-match white point/orange/cuff/skin to official' + ('' if sd == 'r' else ', horizontal mirror (rig screen-left arm)'))
for sd in 'rl':
    for st in ('bent', 'up'):
        p = R / f'parts/ai/arm-{st}-{sd}-hand.png'
        if p.exists(): add(f'parts/ai/arm-{st}-{sd}-hand.png', f'parts/ai/arm-{st}-{sd}.png', 'front copy: hand + cuff region only (alpha mask), drawn above the head group while the arm is raised')
    add(f'parts/ai/arm-hang-{sd}-cap.png', f'parts/ai/arm-hang-{sd}.png', 'shoulder cap: top of the hang sleeve with faded lower edge, static, under the jacket')
out = dict(note='r3: AI-generated arm/sleeve/hand pose-state art supplied by the project owner (generated outside the box because the GenerateImage MCP was unavailable). '
                'Brand lock: hairclip N logo, badge, jacket body, face, hairband, choker are the official layers (sha256-checked by brand-check.py); the AI art is limited to arm pieces.',
           generateImage_status='owner-supplied', license_file='rive/nomi-complete/LICENSE', assets=assets)
(R / 'parts/DETAIL_LICENSE.json').write_text(json.dumps(out, indent=1, ensure_ascii=False) + '\n')
(R / 'LICENSE').write_text('''Nomi·诺米 Rive prototype - AI-generated arm art

ai_generated: true
rive/nomi-complete/gen-src/*.jpg and everything derived from them (rive/nomi-complete/parts/ai/*.png: keyed, cropped,
colour-matched, mirrored and masked copies) are AI-generated artwork. They were generated by the project owner (Cookieboty)
with AI image tools, using the official Nomi half-body illustration (and earlier generated pose/hand images) as reference.
The project owner grants their use in the Nomi-ai repository under the repository's MIT license - the same terms as the
other owner-provided AI-generated mascot artwork (packages/renderer/public/assets/models/sprite/nomi/LICENSE.txt).

Scope: only sleeve / forearm / hand / cuff pieces. The brand-identity parts (hairclip N logo, badge, jacket body, face,
hairband, choker and all head layers) are the official layers in rive/nomi-complete/official/ and are unchanged
(sha256 verified by scripts/rive-complete/brand-check.py). Every AI-generated file is listed with ai_generated: true in
rive/nomi-complete/parts/DETAIL_LICENSE.json.

Files under parts/ not listed with ai_generated: true (r2 official cut/restore textures, procedural patches) contain no
AI-generated pixels and are not embedded in the r3 scene.
''')
print('assets', len(assets), 'ai', sum(1 for v in assets.values() if v['ai_generated']))
